            group_mask = BMI >= group_boundaries(g) & BMI <= group_boundaries(g+1);
        else
            group_mask = BMI >= group_boundaries(g) & BMI < group_boundaries(g+1);
        end
        
        group_indices = find(group_mask);
        
        if isempty(group_indices)
            group_risks(g) = inf;
            optimal_weeks(g) = NaN;
            group_info(g).indices = [];
            group_info(g).precision = 0;
            group_info(g).sample_data = [];
            continue;
        end
        
        % 提取组内数据
        group_gestational = gestational_weeks(group_indices);
        group_Y = Y_concentration(group_indices);
        
        % 寻找最佳检测时间点
        week_candidates = linspace(min(group_gestational), max(group_gestational), 20);
        min_risk = inf;
        best_week = NaN;
        best_precision = 0;
        
        for week = week_candidates
            % 计算在该时间点之后的样本精度
            later_samples_mask = group_gestational >= week;
            if sum(later_samples_mask) == 0
                continue;
            end
            
            later_Y = group_Y(later_samples_mask);
            precision = sum(later_Y > threshold_c) / length(later_Y);
            
            % 计算风险函数
            week_min = min(group_gestational);
            week_max = max(group_gestational);
            
            if week_max == week_min
                normalized_week = 0.5;
            else
                normalized_week = (week - week_min) / (week_max - week_min);
            end
            
            % 实用准则风险函数
            risk = alpha * (1 - precision) + (1 - alpha) * normalized_week;
            
            if risk < min_risk
                min_risk = risk;
                best_week = week;
                best_precision = precision;
            end
        end
        
        group_risks(g) = min_risk;
        optimal_weeks(g) = best_week;
        group_info(g).indices = group_indices;
        group_info(g).precision = best_precision;
        group_info(g).sample_data = [group_gestational, group_Y];
    end
end

