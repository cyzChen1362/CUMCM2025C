%% 绘制函数（放在文件最后）
function plot_risk_curves_for_best_grouping(BMI, gestational_weeks, Y_concentration, best_grouping, best_optimal_weeks, alpha, threshold_c)
    % 绘制最佳分组方式下各组的风险值折线图
    
    n_groups = length(best_grouping) - 1;
    colors = lines(n_groups);
    
    figure('Name', 'Time-Accuracy Tradeoff: Risk vs Week (5 BMI groups)', 'Position', [100, 100, 1200, 800]);
    hold on;
    
    legend_entries = {};
    plot_handles = []; % 存储绘图句柄用于图例
    
    % 定义全局孕周范围用于x轴
    global_week_min = min(gestational_weeks);
    global_week_max = max(gestational_weeks);
    
    for g = 1:n_groups
        % 找到属于当前组的样本
        if g == n_groups
            group_mask = BMI >= best_grouping(g) & BMI <= best_grouping(g+1);
        else
            group_mask = BMI >= best_grouping(g) & BMI < best_grouping(g+1);
        end
        
        group_indices = find(group_mask);
        
        if isempty(group_indices)
            continue;
        end
        
        % 提取组内数据
        group_gestational = gestational_weeks(group_indices);
        group_Y = Y_concentration(group_indices);
        sample_count = length(group_indices);
        
        % 定义组内时间范围
        group_week_min = min(group_gestational);
        group_week_max = max(group_gestational);
        
        % 确保有足够的时间范围来绘制曲线
        if group_week_max - group_week_min < 1
            % 时间范围太小，扩展一点
            group_week_min = group_week_min - 0.5;
            group_week_max = group_week_max + 0.5;
        end
        
        % 生成该组的时间点（至少20个点确保平滑曲线）
        time_points = linspace(group_week_min, group_week_max, 30);
        practical_risk_values = zeros(size(time_points));
        
        for t = 1:length(time_points)
            week = time_points(t);
            
            % 计算在该时间点之后的样本精度
            later_samples_mask = group_gestational >= week;
            
            if sum(later_samples_mask) == 0
                % 如果没有后续样本，使用所有样本
                later_Y = group_Y;
            else
                later_Y = group_Y(later_samples_mask);
            end
            
            precision = sum(later_Y > threshold_c) / length(later_Y);
            
            % 计算标准化时间
            if group_week_max == group_week_min
                normalized_week = 0.5;
            else
                normalized_week = (week - group_week_min) / (group_week_max - group_week_min);
            end
            
            % 实用准则风险函数
            practical_risk_values(t) = alpha * (1 - precision) + (1 - alpha) * normalized_week;
        end
        
        % 绘制风险曲线（确保绘制完整的线条）
        h = plot(time_points, practical_risk_values, ...
                 '-', 'LineWidth', 2.5, 'Color', colors(g,:));
        
        % 存储绘图句柄和图例条目
        plot_handles(end+1) = h;
        legend_entries{end+1} = sprintf('组%d: BMI[%.1f-%.1f] (n=%d)', ...
            g, best_grouping(g), best_grouping(g+1), sample_count);
        
        % 标记最优点
        if ~isnan(best_optimal_weeks(g))
            % 找到最优点对应的风险值
            [~, optimal_idx] = min(abs(time_points - best_optimal_weeks(g)));
            scatter(best_optimal_weeks(g), practical_risk_values(optimal_idx), 80, colors(g,:), ...
                    'filled', 'MarkerEdgeColor', 'black', 'LineWidth', 2);
        end
        
        % 调试信息
        fprintf('组%d: BMI[%.1f-%.1f], 样本数=%d, 时间范围=[%.1f-%.1f]\n', ...
            g, best_grouping(g), best_grouping(g+1), sample_count, group_week_min, group_week_max);
    end
    
    % 设置图表属性
    xlabel('Gestational age threshold (weeks)', 'FontSize', 12, 'FontWeight', 'bold');
    ylabel('Risk', 'FontSize', 12, 'FontWeight', 'bold');
    title('Time-Accuracy Tradeoff: Risk vs Week (5 BMI groups)', 'FontSize', 14, 'FontWeight', 'bold');
    
    % 设置坐标轴范围
    xlim([global_week_min, global_week_max]);
    ylim([0, 1]);
    
    % 使用绘图句柄创建图例，确保颜色正确对应
    legend(plot_handles, legend_entries, 'Location', 'northwest', 'FontSize', 10);
    
    % 设置网格
    grid on;
    set(gca, 'FontSize', 11);
    
    % 设置y轴刻度
    yticks(0:0.1:1);
    
    hold off;
    
    fprintf('Time-Accuracy Tradeoff图表已生成\n');
    
    % 输出各组详细信息
    fprintf('\n各组详细信息:\n');
    for g = 1:n_groups
        if g == n_groups
            group_mask = BMI >= best_grouping(g) & BMI <= best_grouping(g+1);
        else
            group_mask = BMI >= best_grouping(g) & BMI < best_grouping(g+1);
        end
        sample_count = sum(group_mask);
        if sample_count > 0
            group_indices = find(group_mask);
            group_gestational = gestational_weeks(group_indices);
            fprintf('组%d: BMI[%.1f-%.1f] (n=%d), 孕周范围=[%.1f-%.1f]\n', ...
                g, best_grouping(g), best_grouping(g+1), sample_count, ...
                min(group_gestational), max(group_gestational));
        end
    end
end

